// 0359: a document task's review pack opens with a button for each of its files, at the top, and pressing one shows it
// in the panel and nowhere else; speck pack puts the Document section straight after the summary.
import './support/tmp.mjs'; // first: sends every temporary folder into one per-run folder that is cleaned up
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { reviewPack } from '../scripts/pack.mjs';
import { docRepo, PACK, DOCS, text, openPack, pane, docView, docButtons } from './support/documents.mjs';

// The pane's own nodes, top to bottom, and the index of the first one holding `pick`.
const at = (p, pick) => pane(p).children.findIndex(n => p.all(n).includes(pick));

// ---------- AC1: a button per file, at the top ----------

test('0359 AC1: a document task\'s pack has a button per file at the top, above the Ship and Ask for changes row', async () => {
  const p = await openPack({ pack: PACK, documents: DOCS });
  const bs = docButtons(p);
  assert.deepEqual(bs.map(b => b.textContent), DOCS.map(d => d.path), 'one per file, labelled with its path from the project root');
  const all = p.all(pane(p));
  const ship = all.find(n => n.tagName === 'button' && n.textContent === 'Ship');
  const ask = all.find(n => n.tagName === 'button' && n.textContent === 'Ask for changes');
  assert.ok(ship && ask, 'the Ship and Ask for changes row is there');
  const body = pane(p).children.find(n => n.className === 'md');
  for (const b of bs) {
    assert.ok(at(p, b) < at(p, ship) && at(p, b) < at(p, ask), `${b.textContent} is above the Ship row`);
    assert.ok(!p.all(body).includes(b), `${b.textContent} is not in the pack's text`);
  }
});

test('0359 AC1: the files are no longer listed under the acceptance criteria table', async () => {
  const p = await openPack({ pack: PACK, documents: DOCS });
  const body = pane(p).children.find(n => n.className === 'md');
  assert.ok(body.textContent.includes('Acceptance criteria'), 'the pack is shown');
  assert.ok(!body.textContent.includes('Document'), 'no Document heading in the pack');
  for (const d of DOCS) assert.ok(!body.textContent.includes(d.path), `${d.path} is listed once, at the top`);
  assert.equal(p.all(pane(p)).filter(n => n.tagName === 'a').length, 0, 'no links to the files');
});

test('0359 AC1: a pack with no files has no buttons', async () => {
  const p = await openPack({ pack: PACK });
  assert.equal(p.all(pane(p)).filter(n => n.className === 'pack-documents' || n.className === 'pack-document').length, 0);
});

// ---------- AC2: a Markdown file shows in the panel and opens nothing else ----------

test('0359 AC2: a Markdown file\'s button has no address or target, and pressing it shows it formatted and opens nothing', async () => {
  const opened = [];
  const p = await openPack({ pack: PACK, documents: DOCS }, [text('# Pricing\n\nPrices go **up**.\n')], { window: { open: (...a) => opened.push(a) } });
  const md = docButtons(p)[0];
  assert.equal(md.tagName, 'button');
  assert.equal(md.type, 'button');
  assert.equal(md.href, undefined, 'no address');
  assert.equal(md.target, undefined, 'no target');
  p.press(md);
  await p.settle();
  assert.deepEqual(opened, [], 'no new tab or window');
  const all = p.all(docView(p)); // 0362: in a pop-up over the whole panel, not the side pane
  assert.ok(all.some(n => /^h/.test(n.tagName) && n.textContent === 'Pricing'), 'shown formatted in the pop-up');
  assert.ok(all.some(n => n.tagName === 'strong' && n.textContent === 'up'));
});

// ---------- AC3: any other file opens in a new tab, served by the panel ----------

test('0359 AC3: pressing any other file\'s button opens it in a new tab, served by the panel', async () => {
  const opened = [];
  const p = await openPack({ pack: PACK, documents: DOCS }, [], { window: { open: (...a) => opened.push(a) } });
  const pdf = docButtons(p)[1];
  assert.equal(pdf.href, undefined);
  const calls = p.calls.length;
  p.press(pdf);
  await p.settle();
  assert.equal(opened.length, 1);
  assert.equal(opened[0][0], DOCS[1].url, 'the address the panel serves it at');
  assert.equal(opened[0][1], '_blank', 'a new tab');
  assert.match(opened[0][2] || '', /noopener/);
  assert.equal(p.calls.length, calls, 'nothing fetched into the pane');
  assert.ok(pane(p).textContent.includes('Generated by speck'), 'the pack stays');
});

// ---------- AC4: speck pack puts the Document section after the summary ----------

test('0359 AC4: speck pack puts a document task\'s Document section straight after the summary, before the criteria', () => {
  const r = docRepo();
  const out = r.run('pack', '1');
  assert.equal(out.status, 0, out.stderr);
  const lines = out.stdout.split('\n');
  const summary = lines.findIndex(l => l.startsWith('**Summary:**'));
  const doc = lines.indexOf('### Result');
  const ac = lines.indexOf('### Acceptance criteria');
  assert.ok(summary >= 0 && doc >= 0 && ac >= 0, out.stdout);
  assert.ok(summary < doc && doc < ac, 'summary, then Result (Document until 0492), then the criteria');
  assert.ok(lines.slice(summary + 1, doc).every(l => l === ''), 'nothing between the summary and the Result section');
  assert.ok(lines.slice(doc, ac).some(l => l.includes('`outputs/memos/pricing/memo.md`')), 'the files are in it');
  assert.equal(lines.filter(l => l === '### Result').length, 1, 'once');
});

test('0359 AC4: an empty or missing output folder\'s line is there too, before the criteria', () => {
  const r = docRepo({ files: false });
  const pack = reviewPack(r.dir, '1');
  assert.ok(pack.indexOf('### Result') > pack.indexOf('**Summary:**'));
  assert.ok(pack.indexOf('### Result') < pack.indexOf('### Acceptance criteria'));
  assert.ok(!fs.existsSync(`${r.dir}/outputs`), 'speck pack makes no folder');
});
