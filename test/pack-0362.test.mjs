// 0362: a document task's Markdown file opens, formatted, in a pop-up over the whole panel rather than in the side pane,
// and closing it leaves the review pack as it was, with the focus back on the file's button.
import './support/tmp.mjs'; // first: sends every temporary folder into one per-run folder that is cleaned up
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { page, pageScript, styles } from './support/panel.mjs';
import { PACK, DOCS, text, openPack, pane, docView, docButtons } from './support/documents.mjs';

const MEMO = '# Pricing\n\nPrices go **up**.\n\n| Plan | Price |\n|---|---|\n| Basic | £5 |\n';
// The declarations of each CSS rule whose selector list holds exactly `sel`, in the page's style, media queries included.
const rules = sel => {
  const css = styles().replace(/\/\*[\s\S]*?\*\//g, '');
  return [...css.matchAll(/([^{}]+)\{([^{}]*)\}/g)].filter(m => m[1].replace(/^[^{]*\{/, '').split(',').map(x => x.trim()).includes(sel)).map(m => m[2]);
};
const rule = sel => rules(sel)[0] || '';
// A page where each node can take the focus, and `p.focused()` is the node holding it.
async function focusPack(responses) {
  let focused = null;
  const focusable = n => { n.focus = () => { focused = n; }; return n; };
  const p = await openPack({ pack: PACK, documents: DOCS }, responses, {}, focusable);
  for (const id of ['full-ticket', 'doc-view']) focusable(p.byId(id));
  p.focused = () => focused;
  return p;
}
const within = (n, box) => { for (; n; n = n.parentNode) if (n === box) return true; return false; };
const closeOf = p => p.all(docView(p)).find(n => n.tagName === 'button' && n.textContent === 'Close');

// ---------- AC1: a pop-up over the whole panel, the side pane keeping the pack ----------

test('0362 AC1: pressing a Markdown file opens a pop-up with its path, a Close button and the document formatted, tables included', async () => {
  const p = await focusPack([text(MEMO)]);
  assert.equal(p.all(docView(p)).length, 1, 'empty until a file is pressed');
  p.press(docButtons(p)[0]);
  await p.settle();
  const v = docView(p), all = p.all(v);
  assert.equal(v.hidden, false, 'open');
  assert.match(page().match(/<div id="doc-view"[^>]*>/)?.[0] || '', /role="dialog" aria-modal="true"/, 'a modal dialog');
  assert.ok(v.textContent.includes(DOCS[0].path), 'its path');
  assert.ok(closeOf(p), 'a Close button');
  assert.ok(all.some(n => /^h/.test(n.tagName) && n.textContent === 'Pricing'), 'its heading, formatted');
  assert.ok(all.some(n => n.tagName === 'strong' && n.textContent === 'up'), 'its bold');
  assert.ok(all.some(n => n.tagName === 'table') && all.some(n => n.tagName === 'td' && n.textContent === '£5'), 'its table');
});

test('0362 AC1: the side pane no longer shows the document: it keeps the review pack, with no way back button', async () => {
  const p = await focusPack([text(MEMO)]);
  p.press(docButtons(p)[0]);
  await p.settle();
  const all = p.all(pane(p));
  assert.ok(pane(p).textContent.includes('Generated by speck'), 'the pack stays');
  assert.ok(!all.some(n => /^h/.test(n.tagName) && n.textContent === 'Pricing'), 'not the document');
  assert.ok(!all.some(n => n.tagName === 'button' && n.textContent === 'Back to the review pack'));
  assert.ok(!(page() + pageScript()).includes('Back to the review pack'), 'the button is gone');
});

test('0362 AC1: the pop-up covers the whole window at every width, in colours from the look, with the text in a centred column at most 760 px wide', () => {
  const v = rule('#doc-view');
  assert.match(v, /position: fixed/);
  assert.match(v, /inset: 0/);
  assert.ok(!/(?:^|;)\s*(max-)?width:/.test(v), 'no width of its own: it fills the window');
  assert.match(v, /background: var\(--panel\)/, 'the look\'s own colour, light or dark');
  assert.equal(rules('#doc-view').length, 1, 'no other size at any width');
  const col = rules('#doc-view .md'), margins = col.filter(r => /(^|;)\s*margin:/.test(r));
  assert.ok(col.some(r => /max-width: 760px/.test(r)), 'at most 760 px wide');
  assert.match(margins.at(-1) || '', /margin: 0 auto/, 'centred, by the last rule that sets its margin');
  assert.match(rule('#doc-view[hidden]'), /display: none/);
});

// ---------- AC2: nothing behind it can be reached, the focus moves in and it scrolls on its own ----------

test('0362 AC2: while the pop-up is open, the side pane and everything behind it is inert, and the focus is in the pop-up', async () => {
  const p = await focusPack([text(MEMO)]);
  p.press(docButtons(p)[0]);
  await p.settle();
  for (const id of ['full-ticket', 'full-backdrop']) assert.equal(p.byId(id).inert, true, `${id} can't be clicked or reached with Tab`);
  assert.notEqual(docView(p).inert, true, 'the pop-up itself can be used');
  assert.ok(within(p.focused(), docView(p)), 'the focus is in the pop-up');
});

test('0362 AC2: a long document scrolls inside the pop-up, and the page behind stays held', () => {
  const v = rule('#doc-view');
  assert.match(v, /overflow-y: auto/);
  assert.match(v, /overscroll-behavior: contain/, 'scrolling past its end doesn\'t move the page behind');
  assert.match(rule('html.held'), /overflow: hidden/, 'the page behind is held while the pane is open');
  assert.equal(page().match(/<div id="doc-view"[^>]*>/)?.[0].includes('tabindex="-1"'), true, 'it can take the focus');
});

// ---------- AC3: Close and Escape close it, leaving the pack as it was ----------

for (const [how, close] of [['Close', p => p.press(closeOf(p))], ['Escape', p => p.key('Escape')]]) {
  test(`0362 AC3: ${how} closes the pop-up and leaves the review pack open in the side pane as it was, the focus on the file's button`, async () => {
    const p = await focusPack([text(MEMO)]);
    const before = [...pane(p).children], button = docButtons(p)[0];
    p.press(button);
    await p.settle();
    close(p);
    await p.settle();
    assert.equal(docView(p).hidden, true, 'closed');
    assert.equal(pane(p).hidden, false, 'the side pane is still open');
    assert.deepEqual(pane(p).children, before, 'with the same nodes, as it was');
    assert.ok(pane(p).textContent.includes('Generated by speck'));
    assert.equal(p.focused(), button, 'the focus back on the file\'s button');
    for (const id of ['full-ticket', 'full-backdrop']) assert.equal(p.byId(id).inert, false, `${id} can be used again`);
  });
}

test('0362 AC3: an answer that comes after the pop-up has closed is dropped', async () => {
  let settle;
  const p = await focusPack([new Promise(r => { settle = r; })]);
  p.press(docButtons(p)[0]);
  await p.settle();
  p.key('Escape');
  settle({ ok: true, status: 200, text: async () => MEMO });
  await p.settle();
  assert.equal(docView(p).hidden, true);
  assert.equal(p.all(docView(p)).length, 1, 'nothing drawn in it');
});

// ---------- AC4: loading and errors in the pop-up; other files as before ----------

test('0362 AC4: while the file is loading, the pop-up says so, as the side pane did', async () => {
  const p = await focusPack([new Promise(() => {})]);
  p.press(docButtons(p)[0]);
  await p.settle();
  assert.equal(docView(p).hidden, false);
  assert.ok(docView(p).textContent.includes(`Loading ${DOCS[0].path}…`), docView(p).textContent);
});

test('0362 AC4: a file that can\'t be found or fetched says so in the pop-up, with the same wording as before', async () => {
  for (const [answer, said] of [[{ status: 404, body: null }, `Couldn't open ${DOCS[0].path}: the panel didn't find it (404).`],
    [new Error('down'), `Couldn't reach the panel server, so ${DOCS[0].path} can't be shown.`]]) {
    const p = await focusPack([answer]);
    p.press(docButtons(p)[0]);
    await p.settle();
    assert.ok(docView(p).textContent.includes(said), docView(p).textContent);
    assert.ok(closeOf(p), 'with a Close button');
  }
});

test('0362 AC4: a file that isn\'t Markdown still opens in a new tab, and no pop-up', async () => {
  const opened = [];
  const p = await openPack({ pack: PACK, documents: DOCS }, [], { window: { open: (...a) => opened.push(a) } });
  p.press(docButtons(p)[1]);
  await p.settle();
  assert.deepEqual(opened.map(a => a.slice(0, 2)), [[DOCS[1].url, '_blank']]);
  assert.equal(p.all(docView(p)).length, 1, 'no pop-up');
});

test('0362 AC3: when the ticket leaves the board while its document is open, the pop-up closes with the side pane', async () => {
  const p = await focusPack([text(MEMO), { ideas: [], tickets: [] }]);
  p.press(docButtons(p)[0]);
  await p.settle();
  assert.equal(docView(p).hidden, false);
  p.timers.shift()(); // the board's next refresh, without the ticket
  await p.settle();
  assert.equal(pane(p).hidden, true, 'the side pane has closed');
  assert.equal(docView(p).hidden, true, 'and the pop-up with it');
  for (const id of ['full-ticket', 'full-backdrop']) assert.equal(p.byId(id).inert, false);
});
