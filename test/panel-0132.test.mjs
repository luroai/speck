// 0132: the panel opens an approved or shipped ticket's review pack, as `speck pack <id>` prints it, formatted.
import './support/tmp.mjs'; // first: sends every temporary folder into one per-run folder that is cleaned up
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { panelRepo, freePort, startPanel, stop, request, fakePage, T, queueRows, shippedRows, deferred } from './support/panel.mjs';
import { shipRepo } from './support/ship.mjs';

const pane = p => p.byId('full-ticket');
const packButtons = (p, n) => p.all(n).filter(x => x.tagName === 'button' && x.textContent === 'Review pack');
const tags = (p, n, tag) => p.all(n).filter(x => x.tagName === tag);
const ago = min => new Date(Date.now() - min * 60000).toISOString();
const STATE = { ideas: [], tickets: [
  T('0005', 'approved', { started: ago(30) }), T('0006', 'building', { started: ago(10) }), T('0007', 'ready'),
  T('0009', 'done', { started: ago(90), finished: ago(60) }), T('0010', 'done', { started: ago(50), finished: ago(20) }),
] };
const clone = s => JSON.parse(JSON.stringify(s));

// A pack with everything `speck pack` prints: headings, bold, a table with an escaped pipe, lists, the findings in a
// <details> element, and italics. Its text has HTML that must stay text.
const PACK = [
  '## 0005 · Ticket 0005',
  '**Verdict:** ✅ Approved by reviewer (codex, model default, effort default, round 2 of 3)',
  '',
  '**Summary:** All good <script>alert(1)</script>.',
  '',
  '### Acceptance criteria',
  '| # | Criterion | Result | Evidence |',
  '|---|---|---|---|',
  '| 1 | One. | ✅ | `test/a.mjs` passes \\| really |',
  '| 2 | Two. | ❌ | <b>missing</b> |',
  '',
  '### Risk',
  '- Ticket risk: **low**',
  '- No sensitive file patterns touched',
  '',
  '### Review history',
  '- Round 1 (codex, model default, effort default): **request_changes**, 1 open blocking, 0 resolved, 0 minor; fresh session',
  '',
  '<details><summary>Findings</summary>',
  '',
  '- **F1** (blocking, resolved) `scripts/a.mjs`: it broke',
  '',
  '</details>',
  '',
  '### Actuals',
  '- Review rounds: 2',
  '',
  '_Generated by speck. The merge decision is yours._',
].join('\n');

const LOG = { text: '', truncated: false };
// Opens a queue row, as a click on its top row does, which also fetches its log.
const openRow = async (p, row) => { p.press(row.children.find(n => n.className === 'top')); await p.settle(); };

// Opens the pack from a row, after opening the row first if it's in the queue.
async function openPack(row, response = { pack: PACK }) {
  const queued = row === approvedRow;
  const p = fakePage([clone(STATE), ...(queued ? [LOG] : []), response, clone(STATE)]);
  await p.settle();
  if (queued) await openRow(p, row(p));
  const b = packButtons(p, row(p))[0];
  assert.ok(b, 'the row has a Review pack button');
  p.press(b);
  await p.settle();
  return p;
}
const approvedRow = p => queueRows(p).find(n => n.textContent.includes('0005'));
const shippedRow = p => shippedRows(p).find(n => n.textContent.includes('0010'));

test('0132 AC1: each approved ticket in the queue, once opened, and each Shipped row has a Review pack button, and no other row', async () => {
  const p = fakePage([clone(STATE), LOG, LOG, LOG, clone(STATE)]);
  await p.settle();
  assert.equal(queueRows(p).length, 3);
  for (const r of queueRows(p)) assert.equal(packButtons(p, r).length, 0, 'closed, a row keeps to its top row and bar, as 0069 has it');
  for (let i = 0; i < 3; i++) await openRow(p, queueRows(p)[i]);
  for (const r of queueRows(p)) {
    assert.ok(r.children.some(n => n.className === 'log'), 'the row is open');
    assert.equal(packButtons(p, r).length, r.textContent.includes('0005') ? 1 : 0, r.textContent.slice(0, 20));
  }
  const shipped = shippedRows(p);
  assert.equal(shipped.length, 2);
  for (const r of shipped) assert.equal(packButtons(p, r).length, 1);
  assert.equal(packButtons(p, p.byId('shaping')).length, 0);
});

test('0132 AC1: the button opens that ticket\'s review pack in the side pane', async () => {
  for (const [row, id] of [[approvedRow, '0005'], [shippedRow, '0010']]) {
    const p = await openPack(row);
    assert.equal(p.calls.at(-1).url, `/api/tickets/${id}/pack`);
    assert.equal(pane(p).hidden, false, 'the pane is open');
    assert.ok(pane(p).textContent.includes(id), 'it names the ticket');
    assert.ok(pane(p).textContent.includes('Review pack'), 'it says it is the review pack');
    assert.ok(pane(p).textContent.includes('Approved by reviewer'), 'it shows the pack');
  }
});

test('0132 AC2: the pack\'s headings, table and lists are formatted, not shown as raw Markdown', async () => {
  const p = await openPack(approvedRow);
  const n = pane(p);
  const text = n.textContent;
  for (const raw of ['## ', '### ', '|---|', '**', '<details>', '</details>', '<summary>', '_Generated'])
    assert.ok(!text.includes(raw), `no raw ${raw}`);
  const headings = [...tags(p, n, 'h5'), ...tags(p, n, 'h6')].map(h => h.textContent);
  for (const h of ['0005 · Ticket 0005', 'Acceptance criteria', 'Risk', 'Review history', 'Actuals']) assert.ok(headings.includes(h), `heading ${h}`);
  const table = tags(p, n, 'table');
  assert.equal(table.length, 1, 'one table');
  assert.deepEqual(tags(p, table[0], 'th').map(c => c.textContent), ['#', 'Criterion', 'Result', 'Evidence']);
  const cells = tags(p, table[0], 'tr').slice(1).map(r => tags(p, r, 'td').map(c => c.textContent));
  assert.deepEqual(cells, [['1', 'One.', '✅', 'test/a.mjs passes | really'], ['2', 'Two.', '❌', '<b>missing</b>']]);
  assert.ok(tags(p, table[0], 'code').some(c => c.textContent === 'test/a.mjs'), 'a code span in a cell');
  assert.ok(tags(p, n, 'li').some(li => li.textContent === 'Ticket risk: low'), 'a list');
  assert.ok(tags(p, n, 'strong').some(s => s.textContent === 'Verdict:'), 'bold');
  assert.ok(tags(p, n, 'em').some(s => s.textContent === 'Generated by speck. The merge decision is yours.'), 'italics');
  const details = tags(p, n, 'details');
  assert.equal(details.length, 1, 'the findings fold away');
  assert.equal(tags(p, details[0], 'summary')[0].textContent, 'Findings');
  assert.ok(tags(p, details[0], 'li').some(li => li.textContent === 'F1 (blocking, resolved) scripts/a.mjs: it broke'));
  assert.ok(text.includes('All good <script>alert(1)</script>.'), 'HTML in the text stays text');
  assert.ok(!p.all(n).some(x => ['script', 'b'].includes(x.tagName)), 'no HTML was made from it');
});

test('0132 AC3: a ticket with no review rounds says there\'s no review pack, and shows no error', async () => {
  const p = await openPack(shippedRow, { pack: null });
  const text = pane(p).textContent;
  assert.ok(text.includes('There\'s no review pack for 0010'), text);
  assert.ok(!p.all(pane(p)).some(x => /\bbad\b/.test(x.className || '')), 'nothing shown as an error');
});

test('0132 AC2: a refusal from the server shows its reason in the pane', async () => {
  const p = await openPack(approvedRow, { status: 409, body: { error: 'Found 2 branches for ticket 0005.' } });
  assert.ok(pane(p).textContent.includes('Found 2 branches for ticket 0005.'));
});

test('0132 AC2 (self-check): a pack that arrives after its pane was closed, or replaced by the full ticket, isn\'t shown', async () => {
  const late = deferred();
  const p = fakePage([clone(STATE), late, clone(STATE)]);
  await p.settle();
  p.press(packButtons(p, shippedRow(p))[0]);
  await p.settle();
  assert.ok(pane(p).textContent.includes('Loading the review pack'));
  p.key('Escape');
  late.resolve({ ok: true, status: 200, json: async () => ({ pack: PACK }) });
  await p.settle();
  assert.equal(pane(p).hidden, true, 'still closed');
  const later = deferred();
  const q = fakePage([clone(STATE), later, clone(STATE)]);
  await q.settle();
  q.press(packButtons(q, shippedRow(q))[0]);
  await q.settle();
  q.press(q.all(shippedRow(q)).find(x => x.tagName === 'button' && x.textContent === 'Full ticket'));
  later.resolve({ ok: true, status: 200, json: async () => ({ pack: PACK }) });
  await q.settle();
  assert.ok(!pane(q).textContent.includes('Approved by reviewer'), 'the full ticket stays');
  assert.ok(!pane(q).textContent.includes('Review pack'));
});

test('0132 AC2 AC4: the server sends `speck pack`\'s text for an approved and a shipped ticket, and changes no file', async () => {
  const r = shipRepo();
  const p = await startPanel(r.dir, ['--port', String(await freePort())]);
  try {
    const before = r.snapshot();
    const res = await request(p.port, { pathName: '/api/tickets/1/pack' });
    assert.equal(res.status, 200);
    const cli = r.run('pack', '1');
    assert.equal(cli.status, 0, cli.stderr);
    assert.equal(JSON.parse(res.body).pack, cli.stdout.replace(/\n$/, ''));
    assert.deepEqual(r.snapshot(), before, 'nothing changed');
    assert.equal(r.g('status', '--porcelain'), '', 'no new or changed file');
  } finally { await stop(p); }
  const shipped = r.run('ship', '1');
  assert.equal(shipped.status, 0, shipped.stderr + shipped.stdout);
  const p2 = await startPanel(r.dir, ['--port', String(await freePort())]);
  try {
    const before = r.g('status', '--porcelain'), head = r.g('rev-parse', 'HEAD');
    const res = await request(p2.port, { pathName: '/api/tickets/1/pack' });
    assert.equal(res.status, 200);
    const cli = r.run('pack', '1');
    assert.equal(cli.status, 0, cli.stderr);
    assert.match(JSON.parse(res.body).pack, /Approved by reviewer/);
    assert.equal(JSON.parse(res.body).pack, cli.stdout.replace(/\n$/, ''));
    assert.equal(r.g('status', '--porcelain'), before, 'nothing changed');
    assert.equal(r.g('rev-parse', 'HEAD'), head);
  } finally { await stop(p2); }
});

test('0132 AC3: for a ticket with no review rounds the server answers with no pack and no error', async () => {
  const r = panelRepo();
  const p = await startPanel(r.dir, ['--port', String(await freePort())]);
  try {
    const res = await request(p.port, { pathName: '/api/tickets/1/pack' });
    assert.equal(res.status, 200);
    assert.deepEqual(JSON.parse(res.body), { pack: null });
    const missing = await request(p.port, { pathName: '/api/tickets/42/pack' });
    assert.equal(missing.status, 404);
    assert.match(JSON.parse(missing.body).error, /42/);
    assert.equal(r.g('status', '--porcelain'), '', 'nothing changed');
  } finally { await stop(p); }
});
