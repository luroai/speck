// 0354: a document task's review pack lists each file in its output folder, and the panel opens it: a Markdown file
// formatted in the panel (a pop-up since 0362), any other file in a new tab, served only from inside that folder.
import './support/tmp.mjs'; // first: sends every temporary folder into one per-run folder that is cleaned up
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { reviewPack, panelPack } from '../scripts/pack.mjs';
import { documentFile } from '../scripts/output.mjs';
import { shipRepo } from './support/speck.mjs';
import { startPanel, freePort, stop, raw, request } from './support/panel.mjs';
import { docRepo, PACK, DOCS, text, openPack, pane, docView, docButtons } from './support/documents.mjs';

// ---------- AC1: speck pack lists the files ----------

test('0354 AC1: a document task\'s pack lists each file in its output folder, with its path from the project root', () => {
  const r = docRepo();
  const out = r.run('pack', '1');
  assert.equal(out.status, 0, out.stderr);
  for (const f of ['outputs/memos/pricing/drafts/first.md', 'outputs/memos/pricing/figures.pdf', 'outputs/memos/pricing/memo.md'])
    assert.ok(out.stdout.includes(`\`${f}\``), f);
  assert.ok(!out.stdout.includes('secret.txt'), 'only the ticket\'s own folder');
  assert.ok(!out.stdout.includes(fs.realpathSync(r.dir)), 'paths from the project root, not absolute');
});

test('0354 AC1: a document task whose folder is empty or missing says so, and the pack makes nothing', () => {
  const r = docRepo({ files: false });
  assert.match(reviewPack(r.dir, '1'), /outputs\/memos\/pricing\/[^\n]*(doesn't exist|nothing)/);
  assert.ok(!fs.existsSync(path.join(r.dir, 'outputs')), 'speck pack makes no folder');
  fs.mkdirSync(r.out, { recursive: true });
  assert.match(reviewPack(r.dir, '1'), /outputs\/memos\/pricing\/[^\n]*(empty|nothing)/);
});

test('0354 AC1: a code ticket\'s pack is unchanged', () => {
  const r = shipRepo();
  fs.mkdirSync(path.join(r.dir, 'outputs'), { recursive: true });
  fs.writeFileSync(path.join(r.dir, 'outputs', 'stray.md'), 'x\n');
  const pack = reviewPack(r.dir, '1');
  assert.ok(!pack.includes('outputs/'));
  assert.ok(!/Document/.test(pack));
  assert.deepEqual(Object.keys(panelPack(r.dir, '1').body), ['pack'], 'the panel gets the pack alone, as before');
});

// ---------- AC2: the panel links to each file ----------

test('0354 AC2: the panel server lists each file with the address it serves it at, and leaves them out of the text', () => {
  const r = docRepo();
  const out = panelPack(r.dir, '1');
  assert.equal(out.status, 200);
  assert.deepEqual(out.body.documents, [
    { path: 'outputs/memos/pricing/drafts/first.md', url: '/api/tickets/0001/output/drafts/first.md' },
    { path: 'outputs/memos/pricing/figures.pdf', url: '/api/tickets/0001/output/figures.pdf' },
    { path: 'outputs/memos/pricing/memo.md', url: '/api/tickets/0001/output/memo.md' },
  ]);
  assert.ok(!out.body.pack.includes('memo.md'), 'the panel shows them itself, as links');
});

// 0359 made each file a button at the top of the pack rather than a link under the criteria: these check what 0354 did
// still holds with the buttons.
test('0354 AC2: each file the pack lists can be pressed; a file that isn\'t Markdown opens in a new tab, served by the panel', async () => {
  const opened = [];
  const p = await openPack({ pack: PACK, documents: DOCS }, [], { window: { open: (...a) => opened.push(a) } });
  const bs = docButtons(p);
  assert.deepEqual(bs.map(b => b.textContent), DOCS.map(d => d.path));
  p.press(bs[1]);
  assert.deepEqual(opened.map(a => a.slice(0, 2)), [[DOCS[1].url, '_blank']]);
});

// 0362 moved a Markdown file from the side pane into a pop-up over the whole panel, which Close closes, back to the pack.
test('0354 AC2: pressing a Markdown file shows it formatted in a pop-up, and closing it goes back to the pack', async () => {
  const p = await openPack({ pack: PACK, documents: DOCS }, [text('# Pricing\n\nPrices go **up**.\n')]);
  p.press(docButtons(p)[0]);
  await p.settle();
  assert.ok(p.calls.some(c => c.url === DOCS[0].url), 'fetched from the panel');
  const all = p.all(docView(p));
  assert.ok(all.some(n => /^h/.test(n.tagName) && n.textContent === 'Pricing'), 'its heading, formatted');
  assert.ok(all.some(n => n.tagName === 'strong' && n.textContent === 'up'), 'its bold, formatted');
  assert.ok(docView(p).textContent.includes('outputs/memos/memo.md'), 'it says which file it is');
  assert.ok(pane(p).textContent.includes('Generated by speck'), 'the pack stays behind it');
  p.press(all.find(n => n.tagName === 'button' && n.textContent === 'Close'));
  await p.settle();
  assert.equal(docView(p).hidden, true);
  assert.ok(pane(p).textContent.includes('Generated by speck'), 'the pack again');
  assert.equal(docButtons(p).length, 2);
});

test('0354 AC2: a Markdown file that can\'t be fetched says so in the pop-up, with its Close button', async () => {
  const p = await openPack({ pack: PACK, documents: DOCS }, [{ status: 404, body: null }]);
  p.press(docButtons(p)[0]);
  await p.settle();
  assert.match(docView(p).textContent, /couldn't|can't/i);
  assert.ok(p.all(docView(p)).some(n => n.tagName === 'button' && n.textContent === 'Close'));
});

test('0354 AC2: a file the server lists with an address that isn\'t its own is left out', async () => {
  const p = await openPack({ pack: PACK, documents: [...DOCS, { path: 'outputs/x.md', url: 'https://example.com/x.md' }, { path: 'outputs/y.md' }, 'x', null] });
  assert.deepEqual(p.all(pane(p)).filter(n => n.className === 'pack-document').map(b => b.textContent), DOCS.map(d => d.path));
});

// ---------- AC2 and AC3: the panel serves the files, only from inside the folder ----------

test('0354 AC3: documentFile gives only files inside the ticket\'s output folder', () => {
  const r = docRepo();
  assert.equal(documentFile(r.dir, '1', 'memo.md').body.toString(), '# Pricing\n\nPrices go **up**.\n');
  assert.equal(documentFile(r.dir, '1', 'drafts/first.md').body.toString(), 'Draft.\n');
  fs.symlinkSync(path.join(r.dir, 'outputs', 'memos', 'secret.txt'), path.join(r.out, 'link.txt'));
  fs.symlinkSync(path.join(r.dir, 'speck'), path.join(r.out, 'dirlink'));
  for (const bad of ['../secret.txt', 'drafts/../../secret.txt', '/etc/passwd', 'link.txt', 'dirlink/config.yml', 'drafts', '', 'missing.md', 'memo.md\0', '.'])
    assert.equal(documentFile(r.dir, '1', bad), null, JSON.stringify(bad));
  const code = shipRepo();
  fs.mkdirSync(path.join(code.dir, 'outputs'), { recursive: true });
  fs.writeFileSync(path.join(code.dir, 'outputs', 'memo.md'), 'x\n');
  assert.equal(documentFile(code.dir, '1', 'memo.md'), null, 'a code ticket has no output folder');
  assert.equal(documentFile(r.dir, '42', 'memo.md'), null, 'no such ticket');
});

test('0354 AC2 AC3: the panel serves each file in the folder, and a 404 for any path that leads outside it', async () => {
  const r = docRepo();
  fs.symlinkSync(path.join(r.dir, 'outputs', 'memos', 'secret.txt'), path.join(r.out, 'link.txt'));
  fs.writeFileSync(path.join(r.out, 'page.html'), '<script>alert(1)</script>');
  const p = await startPanel(r.dir, ['--port', String(await freePort())]);
  try {
    const memo = await raw(p.port, '/api/tickets/1/output/memo.md');
    assert.equal(memo.status, 200);
    assert.match(memo.headers['content-type'], /^text\/markdown; charset=utf-8/);
    assert.equal(memo.body.toString(), '# Pricing\n\nPrices go **up**.\n');
    const pdf = await raw(p.port, '/api/tickets/0001/output/figures.pdf');
    assert.equal(pdf.status, 200);
    assert.equal(pdf.headers['content-type'], 'application/pdf');
    assert.equal((await raw(p.port, '/api/tickets/1/output/drafts/first.md')).status, 200);
    const html = await raw(p.port, '/api/tickets/1/output/page.html');
    assert.match(html.headers['content-security-policy'] || '', /sandbox/, 'a page the build wrote can\'t act as the panel');
    for (const bad of ['/api/tickets/1/output/../secret.txt', '/api/tickets/1/output/..%2Fsecret.txt', '/api/tickets/1/output/%2e%2e/secret.txt',
      '/api/tickets/1/output/drafts/..%2F..%2Fsecret.txt', '/api/tickets/1/output/link.txt', '/api/tickets/1/output/%2Fetc%2Fpasswd',
      '/api/tickets/1/output/missing.md', '/api/tickets/1/output/%E0%A4%A', '/api/tickets/42/output/memo.md'])
      assert.equal((await request(p.port, { pathName: bad })).status, 404, bad);
  } finally { await stop(p); }
});

test('0354 AC3: a link at the output folder, or at a folder it\'s in, lists nothing and serves nothing', () => {
  for (const linked of ['outputs/memos/pricing', 'outputs/memos', 'outputs']) {
    const r = docRepo({ files: false });
    const elsewhere = fs.mkdtempSync(path.join(path.dirname(r.dir), 'speck-elsewhere-'));
    // The folder the link points at holds what would be the ticket's folder, with a secret in it.
    const inside = path.join(elsewhere, path.relative(path.join(r.dir, linked), r.out));
    fs.mkdirSync(inside, { recursive: true });
    fs.writeFileSync(path.join(inside, 'secret.txt'), 'Outside the project.\n');
    fs.mkdirSync(path.dirname(path.join(r.dir, linked)), { recursive: true });
    fs.symlinkSync(elsewhere, path.join(r.dir, linked));
    assert.equal(fs.readFileSync(path.join(r.out, 'secret.txt'), 'utf8'), 'Outside the project.\n', 'the link leads there');
    assert.equal(documentFile(r.dir, '1', 'secret.txt'), null, linked);
    assert.ok(!reviewPack(r.dir, '1').includes('secret.txt'), linked);
    assert.match(reviewPack(r.dir, '1'), /is a link/, linked);
    assert.equal(panelPack(r.dir, '1').body.documents, undefined, linked);
  }
});
