// ---------- 0473: the pop-ups' script in a file of its own ----------

// What opens, draws, updates and closes the full ticket (with its review pack), a document's pop-up and the Pipeline log.
const POPUP_NAMES = ['openFull', 'fullButton', 'packButton', 'loadPack', 'renderFull', 'fullTicket', 'packPane', 'shipPart', 'shipTicket', 'askForChanges',
  'closeFull', 'returnFocus', 'openDocument', 'drawDoc', 'drawDocActs', 'closeDoc', 'holdPane', 'renderForeman', 'wantRunLog', 'drawRunLog', 'closeForeman',
  'fullId', 'packOf', 'docOpen', 'foremanOpen', 'runLog', 'shippingId', 'shipped', 'changesNotes'];
const declares = (js, name) => new RegExp(`^(?:async function|function|let|const) ${name}\\b`, 'm').test(js);

test('0473 AC1: the full ticket\'s, a document\'s and the Pipeline log\'s script is in templates/panel-popups.js, and panel.js no longer has it', () => {
  assert.equal(POPUPS, path.join(ROOT, 'templates', 'panel-popups.js'));
  const js = popupsScript(), rest = pageScript();
  assert.match(js, /^'use strict';/, 'strict, as the page\'s script is');
  assert.doesNotMatch(js, /<\/?script\b/, 'the file is plain JavaScript');
  assert.doesNotMatch(js, /\{\{\w+\}\}/, 'nothing in it is put in by the server, as it is served as it is');
  for (const name of POPUP_NAMES) {
    assert.ok(declares(js, name), `panel-popups.js has ${name}`);
    assert.ok(!declares(rest, name), `panel.js no longer has ${name}`);
  }
  for (const [what, re] of [['the backdrop\'s click', /\$\('full-backdrop'\)\.addEventListener/], ['the screen\'s press', /\$\('run'\)\.addEventListener/], ['the Pipeline pop-up\'s click', /\$\('foreman'\)\.addEventListener/]]) {
    assert.match(js, re, `${what} is wired up in the pop-ups' file`);
    assert.doesNotMatch(rest, re, `and not in panel.js: ${what}`);
  }
});

test('0473 AC1: on the fake page, the full ticket, a review pack, a document and the Pipeline log each open and close', async () => {
  const p = fakePage([{ tickets: [full('0001')], ideas: [] }]);
  await p.settle();
  const item = () => items(p).find(n => n.textContent.startsWith('0001'));
  click(top(item()));
  click(p.all(item()).find(n => n.tagName === 'button' && n.textContent === 'Full ticket'));
  assert.equal(p.byId('full-ticket').hidden, false, 'the full ticket opens');
  assert.match(p.byId('full-ticket').textContent, /Acceptance criteria/);
  p.key('Escape');
  assert.equal(p.byId('full-ticket').hidden, true, 'and closes');
  p.press(p.byId('run'));
  await p.settle();
  assert.equal(p.byId('foreman').hidden, false, 'the Pipeline log opens');
  assert.match(p.byId('foreman').textContent, /Pipeline[\s\S]*Log/);
  p.key('Escape');
  assert.equal(p.byId('foreman').hidden, true, 'and closes');

  const q = await openPack({ pack: PACK, documents: DOCS }, [text('# Pricing\n')]);
  assert.match(q.byId('full-ticket').textContent, /Review pack[\s\S]*Generated by speck/, 'a review pack opens');
  q.press(q.all(q.byId('full-ticket')).find(n => n.tagName === 'button' && n.textContent === DOCS[0].path));
  await q.settle();
  assert.equal(q.byId('doc-view').hidden, false, 'a document opens');
  assert.match(q.byId('doc-view').textContent, /Pricing/);
  q.key('Escape');
  assert.equal(q.byId('doc-view').hidden, true, 'and closes, leaving the pack');
  assert.equal(q.byId('full-ticket').hidden, false);
});

